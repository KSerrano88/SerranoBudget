CREATE TABLE IF NOT EXISTS recurring_templates (
    ID_TEMPLATE SERIAL PRIMARY KEY,
    DESCRIPTION VARCHAR(100) NOT NULL,
    TRAN_TYPE VARCHAR(50) NOT NULL,
    DIRECTION VARCHAR(6) NOT NULL CHECK (DIRECTION IN ('debit', 'credit')),
    AMOUNT DECIMAL(10,2) CHECK (AMOUNT >= 0),
    NOTES VARCHAR(200) NOT NULL DEFAULT '',
    DAY_OF_MONTH SMALLINT NOT NULL CHECK (DAY_OF_MONTH BETWEEN 1 AND 31),
    POSTED_FLAG SMALLINT NOT NULL DEFAULT 0 CHECK (POSTED_FLAG IN (0, 1))
);

ALTER TABLE transactions ADD COLUMN IF NOT EXISTS RECURRING_TEMPLATE_ID INTEGER
    REFERENCES recurring_templates(ID_TEMPLATE) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS transactions_recurring_template_date
    ON transactions (RECURRING_TEMPLATE_ID, TRANSACTION_DATE);

-- A repeated request returns its saved count without adding the group again.
CREATE TABLE IF NOT EXISTS recurring_batches (
    REQUEST_ID UUID PRIMARY KEY,
    PAYLOAD JSONB NOT NULL,
    TRANSACTION_COUNT INTEGER NOT NULL CHECK (TRANSACTION_COUNT > 0)
);
